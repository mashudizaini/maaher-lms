import { execFileSync } from 'node:child_process';
import { test, expect } from '@playwright/test';

test('admin authors real persisted course content after OIDC; Markdown is inert; publish, archive and logout work', async ({ page, context }) => {
  const account = JSON.parse(execFileSync(process.env.LMS_TEST_PYTHON!,
    [`${process.env.LMS_TEST_ROOT}/scripts/lms01-browser-fixtures.py`, 'oidc-seed'], { input: '{}', encoding: 'utf8' }));
  await page.route('https://browser-tests.us.auth0.com/authorize*', async route => {
    const authorize = new URL(route.request().url()); const state = authorize.searchParams.get('state')!;
    const callback = new URL(authorize.searchParams.get('redirect_uri')!);
    callback.searchParams.set('state', state); callback.searchParams.set('code', state);
    await route.fulfill({ status: 302, headers: { location: callback.toString() } });
  });
  const externalLoads: string[] = [];
  page.on('request', request => { if (request.url().includes('assets.example.invalid')) externalLoads.push(request.url()); });
  await page.goto('/auth');
  await page.getByRole('button', { name: 'Masuk dengan Auth0', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Berhasil masuk melalui Auth0');
  await page.getByRole('button', { name: 'Gunakan organisasi', exact: true }).click();
  await page.getByRole('link', { name: 'Kelola kursus', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Kursus & materi', exact: true })).toBeVisible();
  await page.getByLabel('Judul kursus baru', { exact: true }).fill('Python praktis');
  await page.getByLabel('Deskripsi singkat', { exact: true }).fill('Kursus coding pertama');
  await page.getByRole('button', { name: 'Buat kursus', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Kursus baru dibuat');
  await page.getByRole('button', { name: 'Terbitkan kursus', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Isi setiap modul');
  await page.getByLabel('Judul modul baru', { exact: true }).fill('Dasar Python');
  await page.getByRole('button', { name: 'Tambah modul', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Modul ditambahkan');
  await page.getByRole('button', { name: 'Tambah pelajaran ke Dasar Python', exact: true }).click();
  await page.getByLabel('Judul pelajaran', { exact: true }).fill('Halo Python');
  await page.getByLabel('Materi Markdown', { exact: true }).fill('# Mulai coding\n\n```python\nprint("Halo")\n```\n\n<script>window.__courseXss=1</script>\n\n[Berbahaya](javascript:alert(1))\n\n![Diagram](https://assets.example.invalid/probe.png)');
  await page.getByRole('button', { name: 'Tambah tautan materi', exact: true }).click();
  await page.getByLabel('Nama tautan 1', { exact: true }).fill('Dokumentasi Python');
  await page.getByLabel('URL HTTPS 1', { exact: true }).fill('https://docs.python.org/3/');
  const preview = page.getByRole('article', { name: 'Pratinjau pelajaran' });
  await expect(preview.locator('script,img,a[href^="javascript:"]')).toHaveCount(0);
  await expect(preview.locator('pre')).toContainText('print("Halo")');
  expect(await page.evaluate(() => (window as unknown as { __courseXss?: number }).__courseXss)).toBeUndefined();
  expect(externalLoads).toEqual([]);
  await page.getByRole('button', { name: 'Simpan pelajaran', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Pelajaran disimpan');
  if (process.env.LMS_COURSE_SCREENSHOT) await page.screenshot({ path: process.env.LMS_COURSE_SCREENSHOT, fullPage: true });
  await page.getByRole('button', { name: 'Terbitkan kursus', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Kursus berhasil diterbitkan');
  await page.reload();
  await page.getByRole('button', { name: /Python praktis/ }).click();
  await page.getByRole('button', { name: 'Halo Python', exact: true }).click();
  await expect(page.getByLabel('Materi Markdown', { exact: true })).toHaveValue(/print\("Halo"\)/);
  await expect(preview.getByRole('link', { name: 'Dokumentasi Python', exact: true })).toHaveAttribute('href', 'https://docs.python.org/3/');
  await page.getByLabel('Materi Markdown', { exact: true }).fill('Materi revisi');
  await page.getByRole('button', { name: 'Simpan pelajaran', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Pelajaran disimpan');
  await expect(page.getByRole('button', { name: 'Terbitkan kursus', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Arsipkan kursus', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Kursus diarsipkan');
  await page.getByLabel('Tampilkan arsip').check();
  await page.getByRole('button', { name: /Python praktis/ }).click();
  await page.getByRole('button', { name: 'Pulihkan kursus', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Kursus dipulihkan');
  await page.getByLabel('Tampilkan arsip').uncheck();
  await expect(page.getByRole('button', { name: /Python praktis/ })).toBeVisible();
  const forbidden = await context.request.get('/api/courses', { headers: { 'x-tenant-id': '00000000-0000-0000-0000-000000000000' } });
  expect(forbidden.status()).toBe(403);
  await page.getByRole('link', { name: 'Akun & keluar', exact: true }).click();
  await page.getByRole('button', { name: 'Keluar', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('Berhasil keluar');
  expect((await context.request.get('/api/courses', { headers: { 'x-tenant-id': account.tenant } })).status()).toBe(401);
});

test('course BFF rejects missing/foreign Origin, arbitrary paths, duplicate queries and oversized bodies', async ({ request }) => {
  expect((await request.get('/api/courses')).status()).toBe(401);
  expect((await request.post('/api/courses', { data: { title: 'No origin' } })).status()).toBe(403);
  expect((await request.post('/api/courses', { data: { title: 'Foreign origin' }, headers: { origin: 'https://evil.invalid' } })).status()).toBe(403);
  expect((await request.get('/api/courses/oidc/callback')).status()).toBe(404);
  expect((await request.get('/api/courses?after=bad')).status()).toBe(400);
  expect((await request.get('/api/courses?archived=true&archived=false')).status()).toBe(400);
  expect((await request.post('/api/courses', { data: 'x'.repeat(262145), headers: { origin: process.env.APP_ORIGIN! } })).status()).toBe(413);
});
